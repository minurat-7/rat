function fmt(p) {
  return p.t === '필수' ? `${p.sec} 필수${p.n}` : `${p.sec} EX${p.n}`
}

export function getProblemRange(subjectId, startIdx) {
  const problems = TBALL_PROBLEMS[subjectId]
  if (!problems?.length) return null

  const total = problems.length
  const from = startIdx % total
  const raw = problems.slice(from, from + 10)
  const slice = raw.length < 10
    ? [...raw, ...problems.slice(0, 10 - raw.length)]
    : raw

  const first = slice[0]
  const last = slice[slice.length - 1]

  const firstStr = fmt(first)
  const lastStr = (last.sec === first.sec && last.t === first.t)
    ? last.n
    : fmt(last)

  return `${firstStr} ~ ${lastStr}`
}
